import { describe, expect, it } from 'vitest';
import { parseTokens } from './parse.js';
import { renderCss, renderTs, type TokenSet } from './render.js';

function set(base: unknown, ...themes: [string, unknown][]): TokenSet {
  return {
    base: parseTokens(base),
    themes: themes.map(([name, document]) => ({ name, tokens: parseTokens(document) })),
  };
}

const dark = { color: { $type: 'color', surface: { canvas: { $value: '#0B0C0E' } } } };
const light = { color: { $type: 'color', surface: { canvas: { $value: '#FCFCFD' } } } };

describe('renderCss', () => {
  it('puts base tokens on :root and the first theme on :root and its data-theme', () => {
    const css = renderCss(
      set({ radius: { $type: 'dimension', node: { $value: { value: 6, unit: 'px' } } } }, [
        'dark',
        dark,
      ]),
    );
    expect(css).toContain(':root {\n  --radius-node: 6px;\n}');
    expect(css).toContain(
      ":root,\n[data-theme='dark'] {\n  color-scheme: dark;\n  --color-surface-canvas: #0b0c0e;\n}",
    );
    expect(css).toMatch(/^\/\* Generated by @flowcanvas\/figma-tokens/);
  });

  it('adds later themes under their data-theme attribute only', () => {
    const css = renderCss(set({}, ['dark', dark], ['light', light]));
    expect(css).toContain(
      "[data-theme='light'] {\n  color-scheme: light;\n  --color-surface-canvas: #fcfcfd;\n}",
    );
  });

  it('lets a light theme follow the system preference unless a theme is set explicitly', () => {
    const css = renderCss(set({}, ['dark', dark], ['light', light]));
    expect(css).toContain(
      '@media (prefers-color-scheme: light) {\n  :root:not([data-theme]) {\n    color-scheme: light;\n    --color-surface-canvas: #fcfcfd;\n  }\n}',
    );
  });

  it('does not add a system-preference block when there is no light theme', () => {
    expect(renderCss(set({}, ['dark', dark]))).not.toContain('prefers-color-scheme');
  });

  it('expands typography into one variable per property and resolves references', () => {
    const css = renderCss(
      set(
        {
          font: { family: { $type: 'fontFamily', sans: { $value: ['Inter', 'system-ui'] } } },
          text: {
            $type: 'typography',
            body: {
              $value: {
                fontFamily: '{font.family.sans}',
                fontSize: { value: 13, unit: 'px' },
                fontWeight: 400,
                lineHeight: { value: 20, unit: 'px' },
                letterSpacing: { value: 0, unit: 'px' },
              },
            },
          },
        },
        ['dark', dark],
      ),
    );
    expect(css).toContain('--font-family-sans: Inter, system-ui;');
    expect(css).toContain('--text-body-font-family: var(--font-family-sans);');
    expect(css).toContain('--text-body-font-size: 13px;');
    expect(css).toContain('--text-body-font-weight: 400;');
    expect(css).toContain('--text-body-line-height: 20px;');
    expect(css).toContain('--text-body-letter-spacing: 0px;');
  });

  it('quotes font family names that contain spaces', () => {
    const css = renderCss(
      set(
        {
          font: {
            family: { $type: 'fontFamily', mono: { $value: ['JetBrains Mono', 'monospace'] } },
          },
        },
        ['dark', dark],
      ),
    );
    expect(css).toContain("--font-family-mono: 'JetBrains Mono', monospace;");
  });

  it('formats shadows', () => {
    const css = renderCss(
      set(
        {
          shadow: {
            $type: 'shadow',
            popover: {
              $value: {
                color: 'rgba(0, 0, 0, 0.4)',
                offsetX: { value: 0, unit: 'px' },
                offsetY: { value: 8, unit: 'px' },
                blur: { value: 24, unit: 'px' },
                spread: { value: 0, unit: 'px' },
              },
            },
          },
        },
        ['dark', dark],
      ),
    );
    expect(css).toContain('--shadow-popover: 0px 8px 24px 0px rgba(0, 0, 0, 0.4);');
  });

  it('rejects colours that are not 6-digit hex', () => {
    expect(() =>
      renderCss(set({}, ['dark', { color: { $type: 'color', a: { $value: 'red' } } }])),
    ).toThrow(/color\.a: colors must be 6-digit hex/);
  });

  it('rejects a dimension with an unsupported unit', () => {
    expect(() =>
      renderCss(
        set({ space: { $type: 'dimension', x: { $value: { value: 1, unit: 'em' } } } }, [
          'dark',
          dark,
        ]),
      ),
    ).toThrow(/unit must be one of px, rem/);
  });

  it('rejects a reference to a token that does not exist', () => {
    expect(() =>
      renderCss(set({ a: { $type: 'color', b: { $value: '{color.nope}' } } }, ['dark', dark])),
    ).toThrow(/reference \{color\.nope\} does not point to a token/);
  });

  it('rejects themes that define different tokens', () => {
    expect(() =>
      renderCss(set({}, ['dark', dark], ['light', { color: { $type: 'color' } }])),
    ).toThrow(/theme "light" must define exactly the same tokens as "dark"/);
  });

  it('rejects two token paths that flatten to the same CSS variable', () => {
    const clash = {
      a: { $type: 'number', 'b-c': { $value: 1 } },
      'a-b': { $type: 'number', c: { $value: 2 } },
    };
    expect(() => renderCss(set(clash, ['dark', dark]))).toThrow(/same CSS variable --a-b-c/);
  });

  it('rejects a token defined in both base and a theme', () => {
    expect(() => renderCss(set(dark, ['dark', dark]))).toThrow(/defined more than once/);
  });
});

describe('renderTs', () => {
  it('exports var() references and resolved values per theme', () => {
    const ts = renderTs(set({}, ['dark', dark], ['light', light]));
    expect(ts).toContain('"canvas": "var(--color-surface-canvas)"');
    expect(ts).toContain('"--color-surface-canvas": "#0b0c0e"');
    expect(ts).toContain('"--color-surface-canvas": "#fcfcfd"');
    expect(ts).toContain("export type ThemeName = 'dark' | 'light';");
  });

  it('exports the values that are the same in every theme, for code that needs numbers', () => {
    const ts = renderTs(
      set({ size: { $type: 'dimension', rail: { $value: { value: 44, unit: 'px' } } } }, [
        'dark',
        dark,
      ]),
    );
    expect(ts).toContain('export const baseValues = {');
    expect(ts).toContain('"--size-rail": "44px"');
    // Theme colours stay in themeValues only.
    expect(ts.slice(ts.indexOf('baseValues'))).not.toContain('--color-surface-canvas');
  });
});
